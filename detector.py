"""Small, local MegaDetector V6 ONNX adapter for the Wildlife AI Lab.

No download is performed here. Install numpy, Pillow and onnxruntime once,
then use a local model file. The pretrained model predicts animal/person/
vehicle, not species. Its raw e2e output is [x1,y1,x2,y2,score,class].
"""
from __future__ import annotations

import ast
import hashlib
from pathlib import Path

MODEL_SHA256 = "d38a71b93dcf34147261c6af7665cf3ad2495c924d15503fd88304950cf8eb6a"
MODEL_ID = "MegaDetector V6 MDV6-yolov10-c ONNX (SPARROW bundle)"
INPUT_SIZE = 640
LABELS = {0: "animal", 1: "person", 2: "vehicle"}


class AnimalDetector:
    """CPU-only detector. Boxes are normalized [x,y,width,height]."""

    def __init__(self, model_path, verify_hash=True):
        import onnxruntime as ort

        self.model_path = Path(model_path)
        self.model_sha256 = hashlib.sha256(self.model_path.read_bytes()).hexdigest()
        if verify_hash and self.model_sha256 != MODEL_SHA256:
            raise ValueError("Model hash does not match the tested MDV6 compact model.")
        options = ort.SessionOptions()
        options.intra_op_num_threads = 2
        self.session = ort.InferenceSession(
            str(self.model_path), sess_options=options,
            providers=["CPUExecutionProvider"],
        )
        self.input_name = self.session.get_inputs()[0].name
        if self.session.get_inputs()[0].shape != [1, 3, 640, 640]:
            raise ValueError("Expected fixed model input [1,3,640,640].")
        # The ONNX graph's own names use 'vehicle'; the package's external
        # labels.txt says 'car'. Preserve the graph's broader trained label.
        metadata = self.session.get_modelmeta().custom_metadata_map
        self.labels = ast.literal_eval(metadata.get("names", repr(LABELS)))
        self.runtime_version = ort.__version__

    def predict(self, image, score_floor=0.01):
        """Run genuine inference on the supplied PIL image.

        Pillow bilinear resizing is used by this adapter (the upstream Rust
        runtime uses OpenCV bilinear). Cached results must be generated by
        this same adapter to preserve reproducibility. RGB uint8 pixels are
        letterboxed onto gray 114, converted to NCHW float32, divided by 255.
        No additional NMS is applied: this is a YOLOv10 end-to-end export.
        """
        from PIL import Image, ImageOps
        import numpy as np

        threshold = float(score_floor)
        if not 0 <= threshold <= 1:
            raise ValueError("Confidence threshold must be between 0 and 1.")
        image = ImageOps.exif_transpose(image).convert("RGB")
        width, height = image.size
        if not width or not height:
            raise ValueError("Image must have nonzero width and height.")
        scale = min(INPUT_SIZE / width, INPUT_SIZE / height)
        new_width = max(1, round(width * scale))
        new_height = max(1, round(height * scale))
        left = (INPUT_SIZE - new_width) // 2
        top = (INPUT_SIZE - new_height) // 2
        canvas = Image.new("RGB", (INPUT_SIZE, INPUT_SIZE), (114, 114, 114))
        canvas.paste(image.resize((new_width, new_height), Image.Resampling.BILINEAR), (left, top))
        tensor = np.asarray(canvas, dtype=np.float32).transpose(2, 0, 1)[None] / np.float32(255)
        tensor = np.ascontiguousarray(tensor)
        output = self.session.run(None, {self.input_name: tensor})[0]
        if output.shape != (1, 300, 6):
            raise ValueError(f"Unexpected model output shape: {output.shape}")
        detections = []
        # Use the actual rounded resize ratios when undoing letterboxing.
        scale_x, scale_y = new_width / width, new_height / height
        for x1, y1, x2, y2, score, class_id in output[0]:
            score = float(score)
            if not np.isfinite(score) or score < threshold:
                continue
            class_id = int(class_id)
            if class_id not in self.labels:
                continue
            x1 = min(width, max(0.0, (float(x1) - left) / scale_x))
            x2 = min(width, max(0.0, (float(x2) - left) / scale_x))
            y1 = min(height, max(0.0, (float(y1) - top) / scale_y))
            y2 = min(height, max(0.0, (float(y2) - top) / scale_y))
            if x2 <= x1 or y2 <= y1:
                continue
            detections.append({
                "class_id": class_id,
                "category": self.labels[class_id],
                "score": score,
                "bbox": [x1 / width, y1 / height, (x2 - x1) / width, (y2 - y1) / height],
            })
        return sorted(detections, key=lambda d: d["score"], reverse=True)

    def provenance(self):
        return {
            "model": MODEL_ID,
            "model_sha256": self.model_sha256,
            "onnxruntime_version": self.runtime_version,
            "provider": "CPUExecutionProvider",
            "input_size": [640, 640],
            "preprocessing": "Pillow bilinear letterbox, RGB, padding=114, float32 NCHW / 255",
            "postprocessing": "YOLOv10 e2e xyxy-score-class; undo letterbox; no extra NMS",
            "species_classification": False,
        }
